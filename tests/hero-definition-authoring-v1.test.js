import test from 'node:test';
import assert from 'node:assert/strict';
import {createUserHeroDefinitionV1,validateUserHeroDefinitionV1,createUserHeroAssetResolverV1} from '../src/actors/user-hero-definition-v1.js';

const img=(w=128,h=128)=>({blob:new Blob(['image-bytes'],{type:'image/png'}),width:w,height:h,mimeType:'image/png'});
const base=()=>({id:'hero.user.00000000-0000-4000-8000-000000000001',name:'Explorateur',base:img(),now:'2026-11-04T13:30:00.000Z'});
test('one authored image is enough to create real hero definition using existing simulated movement',()=>{
 const hero=createUserHeroDefinitionV1({...base(),mode:'image'});
 assert.equal(hero.schema,'gensrpg-exploration-user-hero-v1');
 assert.equal(hero.version,1);
 assert.equal(hero.mapVisual.role,'hero');
 assert.equal(hero.mapVisual.animation.mode,'image');
 assert.equal(hero.assets.length,1);
 assert.equal(hero.mapVisual.assetId,hero.assets[0].id);
 assert.equal(hero.assets[0].blob.type,'image/png');
 assert.equal(validateUserHeroDefinitionV1(hero).id,hero.id);
});
test('sprite hero stores explicit idle+walk assets and leaves positions to Exploration',()=>{
 const hero=createUserHeroDefinitionV1({...base(),mode:'frames',framesPerSecond:8,
  idle:[img(),img()],walk:[img(),img(),img()]});
 assert.equal(hero.mapVisual.animation.mode,'frames');
 assert.equal(hero.mapVisual.animation.walk.length,3);
 assert.equal(hero.mapVisual.animation.idle.length,2);
 assert.equal(hero.mapVisual.animation.framesPerSecond,8);
 assert.equal(hero.assets.length,6);
 assert.equal(Object.hasOwn(hero,'x'),false);
 assert.equal(Object.hasOwn(hero,'collision'),false);
 assert.deepEqual([...new Set(hero.assets.map(a=>a.id))],hero.assets.map(a=>a.id));
});
test('reject unsupported image, missing sprites, frames with inconsistent dimensions, unbounded bytes',()=>{
 for(const value of [
  {...base(),base:{...img(),mimeType:'image/svg+xml'}},
  {...base(),mode:'frames',walk:[]},
  {...base(),mode:'frames',walk:[img(100,100)]},
  {...base(),mode:'frames',walk:[{...img(),width:0}]},
  {...base(),mode:'frames',framesPerSecond:0,walk:[img()]},
  {...base(),base:{...img(),blob:new Blob([],{type:'image/png'})}}
 ])assert.throws(()=>createUserHeroDefinitionV1(value));
});
test('visual and assets are reference-only; temporary object URLs revoked after use',()=>{
 const hero=createUserHeroDefinitionV1({...base(),mode:'frames',walk:[img(),img()]});
 const created=[],revoked=[];
 const resolver=createUserHeroAssetResolverV1(hero,{urlApi:{
  createObjectURL(blob){created.push(blob);return 'blob:fake-'+created.length;},
  revokeObjectURL(uri){revoked.push(uri);}
 }});
 assert.equal(resolver.list().length,hero.assets.length);
 assert.equal(resolver.resolve(hero.mapVisual.assetId).path,'blob:fake-1');
 assert.equal(resolver.resolve('unknown'),null);
 resolver.dispose();
 assert.equal(revoked.length,hero.assets.length);
 assert.equal(resolver.list().length,0);
});
test('definition IDs are autogenerated by editor, never raw paths or remote image links',()=>{
 for(const id of ['../hero','https://remote/hero','manual','hero.user.']){
  assert.throws(()=>createUserHeroDefinitionV1({...base(),id,mode:'image'}));
 }
});
