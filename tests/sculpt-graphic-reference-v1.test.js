import test from 'node:test';
import assert from 'node:assert/strict';
import {createSculptTerrain} from '../src/world/sculpt-height-model.js';
import {createComposedObjectDefinitionCatalog} from '../src/objects/object-definition-catalog.js';
import {createUserWorldObjectRecord,objectDefinitionFromUserRecord} from '../src/objects/user-object-library.js';
import {createUserMaterialRecord,composeMaterialPackWithUserMaterials} from '../src/materials/user-material-library.js';
import {createMaterialRegistry} from '../src/materials/material-registry.js';
import {materialPackV1} from '../src/materials/material-pack-v1.js';
import {listSculptPlaceableDefinitions,sculptObjectCanOccupyCell,appendSculptPreviewObject,updateSculptPreviewObject,findSculptPreviewObjectNear,removeSculptPreviewObject,normalizeSculptPreviewObjects,serializeSculptPreviewScene,importSculptPreviewScene} from '../src/world/sculpt-scene-preview.js';
import {createSculptSurface,appendSculptSurfaceStroke,normalizeSculptSurface,removeSculptSurfaceAt} from '../src/world/sculpt-surface-paint.js';
const blob=new Blob(['fixture'],{type:'image/png'});
const image={mimeType:blob.type,bytes:blob.size,blob,width:32,height:32};
test('a personal object uses the canonical catalog and round-trips; absence is explicit',()=>{
 const record=createUserWorldObjectRecord({...image,idToken:'fixture',kind:'decor',label:'Statue',categoryId:'decor',folderId:'decor/general',collisionRole:'obstacle'});
 const catalog=createComposedObjectDefinitionCatalog([objectDefinitionFromUserRecord(record)]);
 const terrain=createSculptTerrain({width:12,height:10});
 assert.ok(listSculptPlaceableDefinitions(catalog).some(x=>x.id===record.definitionId));
 assert.equal(sculptObjectCanOccupyCell(terrain,record.definitionId,2,2,catalog),true);
 const placed=appendSculptPreviewObject([],{definitionId:record.definitionId,x:84,y:63},catalog);
 assert.equal(placed.length,1);
 const edited=updateSculptPreviewObject(placed,placed[0].id,{scale:.8,flipX:true},catalog);
 assert.equal(edited[0].transform.scaleX,.8);
 assert.equal(findSculptPreviewObjectNear(edited,84,63,50,catalog)?.id,placed[0].id);
 const json=serializeSculptPreviewScene(terrain,edited,createSculptSurface(),[],null,[],null,{catalog});
 assert.deepEqual(importSculptPreviewScene(json,{catalog}).objects,edited);
 assert.throws(()=>importSculptPreviewScene(json),/personnelle manquante/);
 assert.throws(()=>normalizeSculptPreviewObjects(edited),/personnelle manquante/);
 assert.equal(removeSculptPreviewObject(edited,edited[0].id,catalog).length,0);
});
test('personal surface and path retain distinct material ids, family and stroke shape',()=>{
 const ground=createUserMaterialRecord({...image,idToken:'grass',kind:'surface',label:'Herbe',terrainFamilyId:'forest'});
 const road=createUserMaterialRecord({...image,idToken:'path',kind:'path',label:'Chemin'});
 const registry=createMaterialRegistry(composeMaterialPackWithUserMaterials(materialPackV1,[ground,road]));
 const terrain=createSculptTerrain({width:12,height:10});
 let paint=normalizeSculptSurface({...createSculptSurface(),baseMaterialId:ground.id},registry);
 paint=appendSculptSurfaceStroke(paint,{materialId:ground.id,points:[{x:60,y:60}],brushShape:'square'},registry);
 paint=appendSculptSurfaceStroke(paint,{materialId:road.id,points:[{x:100,y:100}]},registry);
 assert.equal(paint.zones[0].terrainFamilyId,'forest');assert.equal(paint.zones[0].brushShape,'square');
 assert.equal(paint.routes[0].materialId,road.id);assert.equal(paint.routes[0].traversalRuleId,'terrain.road');
 const json=serializeSculptPreviewScene(terrain,[],paint,[],null,[],null,{materialRegistry:registry});
 assert.deepEqual(importSculptPreviewScene(json,{materialRegistry:registry}).surface,paint);
 assert.throws(()=>importSculptPreviewScene(json),/personnelle manquante/);
 assert.throws(()=>normalizeSculptSurface({...paint,baseMaterialId:road.id},registry),/incompatible/);
 assert.equal(removeSculptSurfaceAt(paint,{x:100,y:100},registry).routes.length,0);
});
